import { readFile, writeFile, stat } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
import yaml from 'js-yaml';
const project = fileURLToPath(new URL('..', import.meta.url));
const pkg = JSON.parse(await readFile(path.join(project, 'package.json'), 'utf8'));
const metadata = yaml.load(await readFile(path.join(project, 'release/latest.yml'), 'utf8'));
const feed = yaml.load(await readFile(path.join(project, 'release/win-unpacked/resources/app-update.yml'), 'utf8'));
assert.equal(metadata.version, pkg.version);
assert.equal(feed.provider, 'github'); assert.equal(feed.owner, 'Lord-GEO'); assert.equal(feed.repo, 'HarborGit'); assert.equal(feed.channel, 'latest');
const name = `HarborGit-${pkg.version}-Setup-x64.exe`;
assert.equal(metadata.path, name);
const file = metadata.files.find(file => file.url === name); assert.ok(file);
const setup = path.join(project, 'release', name), buffer = await readFile(setup);
const sha512 = createHash('sha512').update(buffer).digest('base64');
assert.equal(file.sha512, sha512); assert.equal(metadata.sha512, sha512); assert.equal(file.size, buffer.length);
assert.ok((await stat(`${setup}.blockmap`)).size > 0);
const result = { status: 'passed', version: pkg.version, setup: name, bytes: buffer.length, sha256: createHash('sha256').update(buffer).digest('hex'), sha512, feed, metadata, note: 'Verified actual installer bytes against published metadata; no upload performed.' };
await writeFile(path.join(project, 'docs/verification-v1.3-update-metadata.json'), JSON.stringify(result, null, 2));
console.log(JSON.stringify(result, null, 2));
